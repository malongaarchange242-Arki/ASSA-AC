function applyLanguage(lang) {
    const dict = translations[lang] || translations.fr;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key] !== undefined) {
            el.title = dict[key];
        }
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        if (dict[key] !== undefined) {
            el.setAttribute('aria-label', dict[key]);
        }
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        const key = el.getAttribute('data-i18n-alt');
        if (dict[key] !== undefined) {
            el.alt = dict[key];
        }
    });
    const label = document.getElementById('langLabel');
    if (label) {
        label.textContent = lang.toUpperCase();
    }
    const languageButton = document.getElementById('toggleLang');
    if (languageButton) {
        languageButton.setAttribute('aria-pressed', String(lang === 'en'));
    }
    // update html lang attribute for accessibility
    if (document.documentElement) {
        document.documentElement.lang = lang;
    }
}

// helper usable from other scripts
function t(key) {
    const lang = localStorage.getItem('lang') || 'fr';
    return (translations[lang] && translations[lang][key]) || translations.fr[key] || key;
}
window.t = t;

function setLanguage(lang) {
    localStorage.setItem('lang', lang);
    applyLanguage(lang);
    window.dispatchEvent(new Event('app-language-change'));
}

function toggleLanguage() {
    const current = localStorage.getItem('lang') || 'fr';
    const next = current === 'fr' ? 'en' : 'fr';
    setLanguage(next);
}

document.addEventListener('DOMContentLoaded', () => {
    const lang = localStorage.getItem('lang') || 'fr';
    applyLanguage(lang);
    const btn = document.getElementById('toggleLang');
    if (btn) {
        btn.addEventListener('click', toggleLanguage);
    }
});

// expose for other scripts if needed
window.setLanguage = setLanguage;
window.toggleLanguage = toggleLanguage;